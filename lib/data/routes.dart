List<Poi> poisOf(String routeId) =>
    roadsidePois.where((p) => p.routeId == routeId).toList()
      ..sort((a, b) => a.km.compareTo(b.km));

/// [kmDone] км туулсны дараах хамгийн ойрын шатахуун түгээх станц.
Poi? nextFuel(String routeId, int kmDone) {
  for (final p in poisOf(routeId)) {
    if (p.type == PoiType.fuel && p.km > kmDone) return p;
  }
  return null;
}
