/// [lat], [lng] цэгээс [maxKm] км дотор (ойрхон өөр газрыг андуурахгүй) байгаа хамгийн ойрын газар.
/// Маршрутын зогсоолыг газрын жагсаалттай холбоход ашиглана.
Place? placeNear(double lat, double lng, {double maxKm = 10}) {
  Place? best;
  var bestKm = maxKm;
  for (final p in places) {
    if (!p.hasLocation) continue;
    final km = haversineKm(lat, lng, p.latitude!, p.longitude!);
    if (km <= bestKm) {
      best = p;
      bestKm = km;
    }
  }
  return best;
}
